import 'exceptions.dart';

/// Учебные переключатели поведения сервера.
///
/// В ПР3 переключатель был один и заставлял локальное хранилище бросать
/// исключение. С настоящим сервером роль та же, но способ другой:
/// интерсептор дописывает к запросу параметры `__fail=500` и
/// `__delay=1500`, которые учебный сервер понимает. Так состояние ошибки
/// и индикатор загрузки показываются на настоящих ответах сервера,
/// а не на подделке внутри клиента.
class FaultSwitch {
  bool _enabled = false;
  bool _slow = false;

  /// Сервер обязан ответить ошибкой.
  bool get enabled => _enabled;

  /// Сервер обязан ответить с задержкой.
  bool get slow => _slow;

  /// Код принудительной ошибки и величина задержки — те же, что названы
  /// в задании, чтобы снимки экрана воспроизводились один в один.
  static const int failStatus = 500;
  static const int delayMs = 1500;

  void toggle() => _enabled = !_enabled;

  void toggleSlow() => _slow = !_slow;

  /// Параметры, которые интерсептор дописывает к каждому запросу.
  Map<String, dynamic> get queryParameters => {
    if (_enabled) '__fail': failStatus,
    if (_slow) '__delay': delayMs,
  };

  /// Вызывается локальным репозиторием перед выполнением операции.
  /// Приложение локальными репозиториями больше не пользуется, но на них
  /// стоят проверки ПР3, и поведение отказа там должно сохраниться.
  void throwIfEnabled() {
    if (_enabled) {
      throw const StorageException('Хранилище недоступно');
    }
  }
}
